// دالة تركيب اللوحة (بتستخدم في كل صفحات الأدمن)
function mountAdminLayout(activePage, pageTitle) {
    const sidebarContainer = document.getElementById("sidebar-container");
    const topbarContainer = document.getElementById("topbar-container");

    if (sidebarContainer) {
        sidebarContainer.innerHTML = renderAdminSidebar(activePage);
    }
    if (topbarContainer) {
        topbarContainer.innerHTML = renderAdminTopbar(pageTitle);
    }

    // تفعيل زرار فتح القائمة على الموبايل
    const toggleBtn = document.getElementById("admin-menu-toggle");
    const sidebar = document.getElementById("admin-sidebar");
    if (toggleBtn && sidebar) {
        toggleBtn.addEventListener("click", () => {
            sidebar.classList.toggle("is-open");
        });
    }
}